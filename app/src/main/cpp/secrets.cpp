// XOR encryption key
const uint8_t XOR_KEY = 0x5A;

std::string decryptXor(const uint8_t* encryptedBytes, size_t length) {
    std::string decrypted;
    for (size_t i = 0; i < length; ++i) {
        decrypted += (char)(encryptedBytes[i] ^ XOR_KEY);
    }
    return decrypted;
}

